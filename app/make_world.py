#!/usr/bin/env python3
"""Write app/ui/world-data.js: every country's outline, for the map on the
home screen (app/ui/atlas.js).

    python app/make_world.py ne_50m_admin_0_countries.geojson

The source is Natural Earth's 1:50m admin-0 countries, which is in the public
domain (naturalearthdata.com/about/terms-of-use), fetched from
github.com/nvkelso/natural-earth-vector - geojson/ne_50m_admin_0_countries.geojson.
It is 3 MB; what comes out is under 1 MB, because the outlines are thinned to
about a tenth of a degree. That is finer than a pixel at the closest the
camera ever comes to a country, and the map is lines and fills, not a chart.

Per country (ISO 3166 alpha-2, lower case): the indices of its rings, its
name, the box of its largest polygon (the flag is stretched over that box, so
an overseas territory does not shrink the flag on the mainland) and the
centre of that polygon (where the signal leaves from).
"""

import json
import os
import sys

TOLERANCE = 0.09          # degrees between kept points
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'ui', 'world-data.js')


def thin(ring):
    kept = [ring[0]]
    for p in ring[1:]:
        q = kept[-1]
        if (p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2 >= TOLERANCE * TOLERANCE:
            kept.append(p)
    if len(kept) < 4:
        return None
    flat = []
    for x, y in kept:
        flat += [round(x, 2), round(y, 2)]
    return flat


def area(ring):
    return abs(sum(ring[i][0] * ring[i - 1][1] - ring[i - 1][0] * ring[i][1]
                   for i in range(len(ring)))) / 2


def centroid(ring):
    a = cx = cy = 0.0
    for i in range(len(ring)):
        x0, y0 = ring[i - 1]
        x1, y1 = ring[i]
        c = x0 * y1 - x1 * y0
        a += c
        cx += (x0 + x1) * c
        cy += (y0 + y1) * c
    if not a:
        return ring[0]
    return [round(cx / (3 * a), 2), round(cy / (3 * a), 2)]


NEAR = 2.5               # degrees of open sea that still count as "the same land"


def bounds(ring):
    xs = [p[0] for p in ring]
    ys = [p[1] for p in ring]
    return [min(xs), min(ys), max(xs), max(ys)]


def group_box(rings, main_ring):
    """The box the flag is stretched over: the largest polygon plus every
    polygon lying within NEAR degrees of it, taken in again and again (so
    Canada's Arctic islands, Japan's main islands and Indonesia's chain are
    in, while Alaska, French Guiana or Svalbard, across open sea, are not)."""
    b = bounds(main_ring)
    rest = [bounds(r) for r in rings if r is not main_ring]
    grown = True
    while grown:
        grown = False
        for r in rest[:]:
            gap = max(b[0] - r[2], r[0] - b[2], b[1] - r[3], r[1] - b[3])
            if gap < NEAR:
                b = [min(b[0], r[0]), min(b[1], r[1]), max(b[2], r[2]), max(b[3], r[3])]
                rest.remove(r)
                grown = True
    return b


def main(src):
    with open(src, encoding='utf-8') as f:
        data = json.load(f)
    rings, by, names, box, mid = [], {}, {}, {}, {}
    for feature in data['features']:
        props = feature['properties']
        iso = (props.get('ISO_A2_EH') or props.get('ISO_A2') or '').lower()
        geometry = feature['geometry']
        polys = (geometry['coordinates'] if geometry['type'] == 'MultiPolygon'
                 else [geometry['coordinates']])
        idx = []
        for poly in polys:
            thinned = thin(poly[0])
            if thinned:
                idx.append(len(rings))
                rings.append(thinned)
        if not iso or iso == '-99':
            continue
        by[iso] = idx
        names[iso] = props['NAME']
        main_ring = max(polys, key=lambda p: area(p[0]))[0]
        box[iso] = [round(v, 2) for v in group_box([p[0] for p in polys], main_ring)]
        mid[iso] = centroid(main_ring)
    body = json.dumps({'rings': rings, 'by': by, 'name': names, 'box': box, 'mid': mid},
                      separators=(',', ':'))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Generated by app/make_world.py from Natural Earth 1:50m (public domain). */\n')
        f.write('window.WORLD = ' + body + ';\n')
    print(f'{OUT}: {len(by)} countries, {len(rings)} rings, '
          f'{sum(len(r) // 2 for r in rings)} points, {os.path.getsize(OUT)} bytes')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
