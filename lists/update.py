"""Refresh the Iran lists that split tunnelling reads.

Three files, one per kind of thing a rule can name:

  iran-ipv4.txt     address ranges registered to Iran, as CIDR prefixes
  iran-domains.txt  domains of Iranian services, each meaning itself and
                    everything under it
  iran-apps.txt     Android package names of Iranian apps

Only the first is generated. The ranges come from RIPE NCC's delegation
file - the registry that hands out Iran's addresses, saying which it handed
out - so they are a public record rather than somebody's guess, and they
are the same answer whoever asks. The other two are written by hand: there
is no registry of which .com belongs to an Iranian company, and a wrong
guess there sends somebody's traffic the wrong way, so each line is one a
person put there.

Both apps read the same three files. The desktop reads them from here; the
Android core cannot - Go embeds only what is inside its own module - so
this script also copies them to mobile/core/lists, and a Go test fails if
the copies drift from these.

    python lists/update.py                 download and refresh
    python lists/update.py --from FILE     use a delegation file already
                                           downloaded (and its .md5 beside
                                           it, if there is one)
"""

import argparse
import hashlib
import ipaddress
import os
import shutil
import sys
import time
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GO_COPY = os.path.join(ROOT, 'mobile', 'core', 'lists')
FILES = ('iran-ipv4.txt', 'iran-domains.txt', 'iran-apps.txt')

SOURCE = 'https://ftp.ripe.net/pub/stats/ripencc/delegated-ripencc-latest'


def fetch(url, timeout=120):
    with urllib.request.urlopen(url, timeout=timeout) as r:
        return r.read()


def iran_prefixes(text):
    """Every IPv4 block the file says is Iran's, merged into as few
    prefixes as cover exactly the same addresses.

    A line is `registry|CC|type|start|count|date|status`. The count is a
    number of addresses, not a prefix length, and is not always a power of
    two - so each block is cut into the prefixes that tile it before they
    are merged.
    """
    blocks = []
    for line in text.splitlines():
        p = line.strip().split('|')
        if (len(p) >= 7 and p[1] == 'IR' and p[2] == 'ipv4'
                and p[6] in ('allocated', 'assigned')):
            start = ipaddress.IPv4Address(p[3])
            blocks.extend(ipaddress.summarize_address_range(
                start, start + int(p[4]) - 1))
    return list(ipaddress.collapse_addresses(blocks))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--from', dest='src', help='a delegation file already '
                    'downloaded')
    args = ap.parse_args()

    if args.src:
        raw = open(args.src, 'rb').read()
        md5_path = args.src + '.md5'
        expected = open(md5_path).read() if os.path.exists(md5_path) else ''
    else:
        raw = fetch(SOURCE)
        expected = fetch(SOURCE + '.md5', 60).decode('ascii', 'replace')
    # RIPE publishes an MD5 beside the file. Not a defence against anyone
    # who could change the file, only against a download that was cut short
    # - which on the lines this is for is the likelier of the two.
    if expected:
        got = hashlib.md5(raw).hexdigest()
        if got not in expected:
            sys.exit(f'the download does not match its checksum ({got})')

    text = raw.decode('ascii', 'replace')
    stamp = text.splitlines()[0].split('|')[5] if text else ''
    nets = iran_prefixes(text)
    if len(nets) < 500:
        # Iran has well over a thousand. Far fewer means the file was not
        # the one expected, and an empty list would quietly turn the rule
        # off for everybody.
        sys.exit(f'only {len(nets)} prefixes for IR - not writing that')

    with open(os.path.join(HERE, 'iran-ipv4.txt'), 'w', encoding='utf-8',
              newline='\n') as f:
        f.write('# Address ranges registered to Iran, from RIPE NCC\'s '
                'delegation file\n')
        f.write(f'# ({SOURCE}, {stamp or time.strftime("%Y%m%d")}). '
                'Generated by lists/update.py - do not edit by hand.\n')
        for n in nets:
            f.write(f'{n}\n')

    os.makedirs(GO_COPY, exist_ok=True)
    for name in FILES:
        shutil.copyfile(os.path.join(HERE, name), os.path.join(GO_COPY, name))
    total = sum(n.num_addresses for n in nets)
    print(f'{len(nets)} prefixes, {total:,} addresses; copied to '
          f'{os.path.relpath(GO_COPY, ROOT)}')


if __name__ == '__main__':
    main()
